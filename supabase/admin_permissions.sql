CREATE TABLE IF NOT EXISTS public.permissions_modules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilisateur_id INTEGER NOT NULL REFERENCES public.utilisateurs(id) ON DELETE CASCADE,
  module_key VARCHAR(64) NOT NULL,
  cree_le TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT permissions_modules_utilisateur_module_key
    UNIQUE (utilisateur_id, module_key)
);

CREATE INDEX IF NOT EXISTS permissions_modules_module_key_idx
  ON public.permissions_modules(module_key);

ALTER TABLE public.permissions_modules ENABLE ROW LEVEL SECURITY;

INSERT INTO public.permissions_modules (utilisateur_id, module_key)
SELECT utilisateur.id, module.module_key
FROM public.utilisateurs AS utilisateur
CROSS JOIN (
  VALUES
    ('dashboard'),
    ('transactions'),
    ('dimes'),
    ('categories'),
    ('evenements'),
    ('paudium'),
    ('rapports')
) AS module(module_key)
WHERE utilisateur.role::text <> 'ADMIN'
ON CONFLICT (utilisateur_id, module_key) DO NOTHING;

CREATE OR REPLACE FUNCTION public.rpc_admin_update_access(
  p_actor_id INTEGER,
  p_target_id INTEGER,
  p_actif BOOLEAN,
  p_role TEXT,
  p_module_keys TEXT[],
  p_allowed_module_keys TEXT[]
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor_role TEXT;
  v_actor_actif BOOLEAN;
  v_target_role TEXT;
  v_target_actif BOOLEAN;
  v_active_admin_count INTEGER;
BEGIN
  SELECT role::text, actif
  INTO v_actor_role, v_actor_actif
  FROM public.utilisateurs
  WHERE id = p_actor_id
  FOR UPDATE;

  IF v_actor_role IS DISTINCT FROM 'ADMIN' OR v_actor_actif IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'ADMIN_REQUIRED' USING ERRCODE = 'P0001';
  END IF;

  IF p_target_id = p_actor_id THEN
    RAISE EXCEPTION 'SELF_MODIFICATION_FORBIDDEN' USING ERRCODE = 'P0001';
  END IF;

  PERFORM id
  FROM public.utilisateurs
  WHERE role::text = 'ADMIN' AND actif = TRUE
  ORDER BY id
  FOR UPDATE;

  SELECT role::text, actif
  INTO v_target_role, v_target_actif
  FROM public.utilisateurs
  WHERE id = p_target_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'USER_NOT_FOUND' USING ERRCODE = 'P0001';
  END IF;

  IF p_role IS NOT NULL AND p_role NOT IN ('ADMIN', 'TRESORIER', 'RESPONSABLE', 'AUDITEUR', 'SECRETAIRE') THEN
    RAISE EXCEPTION 'INVALID_ROLE' USING ERRCODE = 'P0001';
  END IF;

  IF p_module_keys IS NOT NULL AND (
    (v_target_role = 'ADMIN' AND p_role IS NULL) OR p_role = 'ADMIN'
  ) THEN
    RAISE EXCEPTION 'ADMIN_PERMISSIONS_IMMUTABLE' USING ERRCODE = 'P0001';
  END IF;

  IF p_module_keys IS NOT NULL AND EXISTS (
    SELECT 1
    FROM unnest(p_module_keys) AS requested(module_key)
    WHERE NOT (requested.module_key = ANY(COALESCE(p_allowed_module_keys, ARRAY[]::TEXT[])))
  ) THEN
    RAISE EXCEPTION 'INVALID_MODULE_PERMISSION' USING ERRCODE = 'P0001';
  END IF;

  IF v_target_role = 'ADMIN'
    AND v_target_actif = TRUE
    AND (p_actif = FALSE OR (p_role IS NOT NULL AND p_role <> 'ADMIN')) THEN
    SELECT COUNT(*)
    INTO v_active_admin_count
    FROM public.utilisateurs
    WHERE role::text = 'ADMIN' AND actif = TRUE;

    IF v_active_admin_count <= 1 THEN
      RAISE EXCEPTION 'LAST_ACTIVE_ADMIN' USING ERRCODE = 'P0001';
    END IF;
  END IF;

  IF p_role IS NULL THEN
    UPDATE public.utilisateurs
    SET
      actif = COALESCE(p_actif, actif),
      modifie_le = NOW()
    WHERE id = p_target_id;
  ELSE
    EXECUTE format(
      'UPDATE public.utilisateurs SET actif = COALESCE($1, actif), role = %L, modifie_le = NOW() WHERE id = $2',
      p_role
    )
    USING p_actif, p_target_id;
  END IF;

  IF p_role = 'ADMIN' THEN
    DELETE FROM public.permissions_modules
    WHERE utilisateur_id = p_target_id;
  END IF;

  IF p_module_keys IS NOT NULL THEN
    DELETE FROM public.permissions_modules
    WHERE utilisateur_id = p_target_id;

    INSERT INTO public.permissions_modules (utilisateur_id, module_key)
    SELECT p_target_id, requested.module_key
    FROM unnest(p_module_keys) AS requested(module_key)
    ON CONFLICT (utilisateur_id, module_key) DO NOTHING;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.rpc_admin_create_user(
  p_actor_id INTEGER,
  p_nom TEXT,
  p_email TEXT,
  p_password_hash TEXT,
  p_role TEXT,
  p_module_keys TEXT[],
  p_allowed_module_keys TEXT[]
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_actor_role TEXT;
  v_actor_actif BOOLEAN;
  v_user_id INTEGER;
BEGIN
  SELECT role::text, actif
  INTO v_actor_role, v_actor_actif
  FROM public.utilisateurs
  WHERE id = p_actor_id
  FOR UPDATE;

  IF v_actor_role IS DISTINCT FROM 'ADMIN' OR v_actor_actif IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'ADMIN_REQUIRED' USING ERRCODE = 'P0001';
  END IF;

  IF p_role NOT IN ('ADMIN', 'TRESORIER', 'RESPONSABLE', 'AUDITEUR', 'SECRETAIRE') THEN
    RAISE EXCEPTION 'INVALID_ROLE' USING ERRCODE = 'P0001';
  END IF;

  IF p_nom IS NULL OR length(trim(p_nom)) < 2 OR length(trim(p_nom)) > 120
    OR p_email IS NULL OR length(p_email) > 191
    OR p_password_hash IS NULL OR length(p_password_hash) < 20 THEN
    RAISE EXCEPTION 'INVALID_USER_DATA' USING ERRCODE = 'P0001';
  END IF;

  IF p_role = 'ADMIN' AND p_module_keys IS NOT NULL THEN
    RAISE EXCEPTION 'ADMIN_PERMISSIONS_IMMUTABLE' USING ERRCODE = 'P0001';
  END IF;

  IF p_role <> 'ADMIN' AND p_module_keys IS NULL THEN
    RAISE EXCEPTION 'MODULE_PERMISSIONS_REQUIRED' USING ERRCODE = 'P0001';
  END IF;

  IF p_module_keys IS NOT NULL AND (
    cardinality(p_module_keys) <> (
      SELECT COUNT(DISTINCT requested.module_key)
      FROM unnest(p_module_keys) AS requested(module_key)
    )
    OR EXISTS (
      SELECT 1
      FROM unnest(p_module_keys) AS requested(module_key)
      WHERE NOT (requested.module_key = ANY(COALESCE(p_allowed_module_keys, ARRAY[]::TEXT[])))
    )
  ) THEN
    RAISE EXCEPTION 'INVALID_MODULE_PERMISSION' USING ERRCODE = 'P0001';
  END IF;

  BEGIN
    EXECUTE format(
      'INSERT INTO public.utilisateurs (nom, email, mot_de_passe, role, actif, modifie_le) VALUES ($1, $2, $3, %L, TRUE, NOW()) RETURNING id',
      p_role
    )
    INTO v_user_id
    USING trim(p_nom), lower(trim(p_email)), p_password_hash;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'USER_EMAIL_EXISTS' USING ERRCODE = 'P0001';
  END;

  IF p_module_keys IS NOT NULL THEN
    INSERT INTO public.permissions_modules (utilisateur_id, module_key)
    SELECT v_user_id, requested.module_key
    FROM unnest(p_module_keys) AS requested(module_key);
  END IF;

  RETURN v_user_id;
END;
$$;

