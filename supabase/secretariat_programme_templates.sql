DO $$
DECLARE
  v_schema TEXT;
  v_type TEXT;
BEGIN
  SELECT enum_namespace.nspname, enum_type.typname
  INTO v_schema, v_type
  FROM pg_attribute AS column_info
  JOIN pg_class AS relation ON relation.oid = column_info.attrelid
  JOIN pg_type AS column_type ON column_type.oid = column_info.atttypid
  LEFT JOIN pg_type AS enum_type
    ON enum_type.oid = CASE
      WHEN column_type.typtype = 'd' THEN column_type.typbasetype
      ELSE column_type.oid
    END
  JOIN pg_namespace AS enum_namespace ON enum_namespace.oid = enum_type.typnamespace
  WHERE relation.oid = to_regclass('public.utilisateurs')
    AND column_info.attname = 'role'
    AND column_info.attnum > 0
    AND NOT column_info.attisdropped
    AND enum_type.typtype = 'e'
  LIMIT 1;

  IF v_type IS NOT NULL THEN
    EXECUTE format(
      'ALTER TYPE %I.%I ADD VALUE IF NOT EXISTS %L',
      v_schema,
      v_type,
      'SECRETAIRE'
    );
  END IF;
END;
$$;

