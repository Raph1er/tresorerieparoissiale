DROP FUNCTION IF EXISTS public.rpc_update_programme_semaine_values(INTEGER, TEXT, JSONB);

CREATE OR REPLACE FUNCTION public.rpc_update_programme_semaine_values(
  p_programme_id INTEGER,
  p_role TEXT,
  p_user_id INTEGER,
  p_fields JSONB
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_structure JSONB;
  v_values JSONB;
  v_admin_fields_complete BOOLEAN;
  v_field RECORD;
BEGIN
  IF p_role NOT IN ('ADMIN', 'SECRETAIRE')
    OR p_user_id IS NULL
    OR p_fields IS NULL
    OR jsonb_typeof(p_fields) <> 'object'
    OR p_fields = '{}'::JSONB THEN
    RAISE EXCEPTION 'INVALID_PROGRAM_FIELDS' USING ERRCODE = 'P0001';
  END IF;

  SELECT structure, valeurs
  INTO v_structure, v_values
  FROM public.programmes_semaine
  WHERE id = p_programme_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'PROGRAM_NOT_FOUND' USING ERRCODE = 'P0001';
  END IF;

  FOR v_field IN
    SELECT requested.key, requested.value
    FROM jsonb_each(p_fields) AS requested(key, value)
  LOOP
    IF jsonb_typeof(v_field.value) <> 'string'
      OR length(v_field.value #>> '{}') > 500
      OR NOT EXISTS (
        SELECT 1
        FROM jsonb_array_elements(v_structure -> 'sections') AS section_data(section_json)
        CROSS JOIN LATERAL jsonb_array_elements(section_data.section_json -> 'champs') AS field_data(field_json)
        WHERE field_data.field_json ->> 'valueKey' = v_field.key
          AND field_data.field_json ->> 'modifiablePar' = p_role
          AND COALESCE((field_data.field_json ->> 'calcule')::BOOLEAN, FALSE) = FALSE
      ) THEN
      RAISE EXCEPTION 'INVALID_PROGRAM_FIELD' USING ERRCODE = 'P0001';
    END IF;
  END LOOP;

  IF p_role = 'ADMIN' THEN
    v_values := v_values || p_fields;
    SELECT NOT EXISTS (
      SELECT 1
      FROM jsonb_array_elements(v_structure -> 'sections') AS section_data(section_json)
      CROSS JOIN LATERAL jsonb_array_elements(section_data.section_json -> 'champs') AS field_data(field_json)
      WHERE field_data.field_json ->> 'modifiablePar' = 'ADMIN'
        AND COALESCE((field_data.field_json ->> 'obligatoire')::BOOLEAN, FALSE)
        AND NULLIF(BTRIM(v_values ->> (field_data.field_json ->> 'valueKey')), '') IS NULL
    )
    INTO v_admin_fields_complete;
  UPDATE public.programmes_semaine
    SET valeurs = v_values,
        statut = CASE
          WHEN v_admin_fields_complete THEN 'A_COMPLETER'
          ELSE 'EN_PREPARATION'
        END,
        modifie_le = NOW()
    WHERE id = p_programme_id;
  ELSE
    INSERT INTO public.programmes_semaine_secretaires AS saisie_existante (
      programme_id, utilisateur_id, valeurs, modifie_le
    )
    VALUES (p_programme_id, p_user_id, p_fields, NOW())
    ON CONFLICT (programme_id, utilisateur_id) DO UPDATE
    SET valeurs = saisie_existante.valeurs || EXCLUDED.valeurs,
        modifie_le = NOW();
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.rpc_update_programme_semaine_values(INTEGER, TEXT, INTEGER, JSONB)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.rpc_update_programme_semaine_values(INTEGER, TEXT, INTEGER, JSONB)
